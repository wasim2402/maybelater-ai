"""Request and response contracts for captures and intentions."""

from __future__ import annotations

from datetime import datetime
from typing import Literal
from uuid import UUID

from pydantic import BaseModel, ConfigDict, Field, field_validator

from app.models.enums import AnalysisStatus, IntentionStatus, SourceType

MAX_CONTENT = 20_000
MAX_NOTE = 1_000


def _clean_text(value: str | None) -> str | None:
    if value is None:
        return None
    value = value.replace("\x00", "").strip()
    return value or None


class CaptureCreate(BaseModel):
    """A text thought or a link. The kind is detected on the server (a single http(s) URL is a link)."""

    model_config = ConfigDict(extra="forbid")

    content: str = Field(min_length=1, max_length=MAX_CONTENT)
    note: str | None = Field(default=None, max_length=MAX_NOTE)
    # One per capture attempt, generated by the client: retrying the same attempt returns the same item.
    client_request_id: UUID | None = None

    @field_validator("content")
    @classmethod
    def _content(cls, value: str) -> str:
        cleaned = _clean_text(value)
        if not cleaned:
            raise ValueError("Write something or paste a link to save.")
        return cleaned

    @field_validator("note")
    @classmethod
    def _note(cls, value: str | None) -> str | None:
        return _clean_text(value)


class CategoryOut(BaseModel):
    id: UUID
    name: str
    slug: str
    is_system: bool


class IntentionOut(BaseModel):
    id: UUID
    source_type: SourceType
    original_content: str
    original_url: str | None
    user_note: str | None
    title: str | None
    summary: str | None
    intent: str | None
    category: CategoryOut | None
    tags: list[str]
    resurface_condition: str | None
    field_states: dict[str, str]
    analysis_status: AnalysisStatus
    status: IntentionStatus
    resurface_at: datetime | None
    snoozed_until: datetime | None
    completed_at: datetime | None
    archived_at: datetime | None
    created_at: datetime
    updated_at: datetime
    # Detail view only: how well the source supported the last suggestions (0-1). A hint, not a guarantee.
    suggestion_confidence: float | None = None


class AnalyzeRequest(BaseModel):
    model_config = ConfigDict(extra="forbid")

    intention_id: UUID


SuggestionField = Literal["title", "summary", "intent", "category", "tags", "resurface_condition"]


class SuggestionDecision(BaseModel):
    """`accept` keeps the suggested value as the user's own; `dismiss` removes it, and it will not be
    suggested again."""

    model_config = ConfigDict(extra="forbid")

    action: Literal["accept", "dismiss"]


class CaptureResult(BaseModel):
    """`created`: saved now. `duplicate`: this link is already open in the inbox (the existing item is
    returned, nothing new is saved). `replayed`: this exact attempt was already saved (a retry)."""

    result: Literal["created", "duplicate", "replayed"]
    item: IntentionOut


StatusFilter = Literal["open", "inbox", "active", "completed", "archived", "all"]


class IntentionPage(BaseModel):
    items: list[IntentionOut]
    next_cursor: str | None


class IntentionUpdate(BaseModel):
    """User edits. Any interpretation field sent here becomes the user's own (`edited`), and later
    AI analysis will not overwrite it. The captured original cannot be changed."""

    model_config = ConfigDict(extra="forbid")

    title: str | None = Field(default=None, max_length=300)
    summary: str | None = Field(default=None, max_length=2000)
    intent: str | None = Field(default=None, max_length=500)
    user_note: str | None = Field(default=None, max_length=MAX_NOTE)
    category_id: UUID | None = None
    tags: list[str] | None = Field(default=None, max_length=20)
    resurface_condition: str | None = Field(default=None, max_length=300)
    status: IntentionStatus | None = None

    @field_validator("title", "summary", "intent", "user_note", "resurface_condition")
    @classmethod
    def _strip(cls, value: str | None) -> str | None:
        return None if value is None else value.replace("\x00", "").strip()

    @field_validator("tags")
    @classmethod
    def _tags(cls, value: list[str] | None) -> list[str] | None:
        if value is None:
            return None
        seen: list[str] = []
        for tag in value:
            cleaned = " ".join(tag.split()).lower()[:40]
            if cleaned and cleaned not in seen:
                seen.append(cleaned)
        return seen
