"""Creates the server's Web Push (VAPID) key pair and saves it in backend/.env.

    .venv\\Scripts\\python.exe scripts\\generate_vapid_keys.py

- Does nothing if keys are already set (changing them would silently break every existing device's
  subscription). Pass --force to replace them; devices then need to turn notifications on again.
- Prints only the public key. The private key is written to .env and never shown.
"""

from __future__ import annotations

import base64
import sys
from pathlib import Path

from cryptography.hazmat.primitives import serialization
from cryptography.hazmat.primitives.asymmetric import ec

ENV = Path(__file__).resolve().parents[1] / ".env"


def b64url(data: bytes) -> str:
    return base64.urlsafe_b64encode(data).rstrip(b"=").decode()


def main() -> int:
    force = "--force" in sys.argv
    lines = ENV.read_text(encoding="utf-8").splitlines() if ENV.exists() else []
    has_keys = any(line.startswith("VAPID_PRIVATE_KEY=") and line.split("=", 1)[1].strip() for line in lines)
    if has_keys and not force:
        print("VAPID keys are already set in backend/.env. Nothing changed (use --force to replace them).")
        return 0

    key = ec.generate_private_key(ec.SECP256R1())
    private = b64url(key.private_numbers().private_value.to_bytes(32, "big"))
    public = b64url(key.public_key().public_bytes(serialization.Encoding.X962, serialization.PublicFormat.UncompressedPoint))

    kept = [line for line in lines if not line.startswith(("VAPID_PUBLIC_KEY=", "VAPID_PRIVATE_KEY="))]
    kept += ["", "# Web Push (reminder notifications). Generated by scripts/generate_vapid_keys.py", f"VAPID_PUBLIC_KEY={public}", f"VAPID_PRIVATE_KEY={private}"]
    ENV.write_text("\n".join(kept).lstrip("\n") + "\n", encoding="utf-8")
    print("Saved a new VAPID key pair to backend/.env.")
    print(f"Public key: {public}")
    print("Restart the API to turn on push notifications.")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
